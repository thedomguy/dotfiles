  group = vim.api.nvim_create_augroup("UserLspAttach", { clear = true }),
  callback = function(ev)
    local map = function(keys, fn, desc)
      vim.keymap.set("n", keys, fn, { buffer = ev.buf, silent = true, desc = "LSP: " .. desc })
    end
    map("gd", vim.lsp.buf.definition,      "Go to definition")
    map("gD", vim.lsp.buf.declaration,     "Go to declaration")
    map("gi", vim.lsp.buf.implementation,  "Go to implementation")
    map("gr", vim.lsp.buf.references,      "References")
    map("gy", vim.lsp.buf.type_definition, "Type definition")
    map("K",  vim.lsp.buf.hover,           "Hover docs")
    map("<leader>rn", vim.lsp.buf.rename,      "Rename symbol")
    map("<leader>ca", vim.lsp.buf.code_action, "Code action")
    map("<leader>e",  vim.diagnostic.open_float, "Line diagnostics")
    map("[d", function() vim.diagnostic.jump({ count = -1 }) end, "Prev diagnostic")
    map("]d", function() vim.diagnostic.jump({ count = 1 })  end, "Next diagnostic")
    map("<leader>lf", function() vim.lsp.buf.format({ async = true }) end, "Format buffer")

    -- Optional signature help while typing arguments.
    vim.keymap.set("i", "<C-s>", vim.lsp.buf.signature_help,
      { buffer = ev.buf, silent = true, desc = "LSP: Signature help" })

    -- Show inlay hints from servers that provide them (roslyn ships many;
    -- toggle per-buffer with <leader>ti). Guard for servers without support.
    local client = vim.lsp.get_client_by_id(ev.data.client_id)
    if client and client:supports_method("textDocument/inlayHint") then
      vim.lsp.inlay_hint.enable(true, { bufnr = ev.buf })
    end
  end,
})

