-- =============================================================
-- Toggleable bottom terminal  (VS Code panel style)
-- =============================================================
-- One persistent terminal in a bottom split. Toggling *hides* the window but
-- keeps the shell/job alive, so the same session comes back — just like VS
-- Code's panel. The last height is remembered across toggles.
-- Pure Lua, no plugin dependency.

local Term = {}
Term._state = { buf = nil, win = nil, height = 15 }

local function term_win_valid()
  return Term._state.win and vim.api.nvim_win_is_valid(Term._state.win)
end
local function term_buf_valid()
  return Term._state.buf and vim.api.nvim_buf_is_valid(Term._state.buf)
end

function Term.open()
  -- Full-width split pinned to the bottom.
  vim.cmd("botright " .. Term._state.height .. "split")
  Term._state.win = vim.api.nvim_get_current_win()

  if term_buf_valid() then
    vim.api.nvim_win_set_buf(Term._state.win, Term._state.buf) -- reuse live shell
  else
    vim.cmd("terminal")
    Term._state.buf = vim.api.nvim_get_current_buf()
    vim.bo[Term._state.buf].buflisted = false
  end

  local w = Term._state.win
  vim.wo[w].number = false
  vim.wo[w].relativenumber = false
  vim.wo[w].signcolumn = "no"
  vim.wo[w].winfixheight = true
  vim.cmd("startinsert")
end

function Term.hide()
  if term_win_valid() then
    Term._state.height = vim.api.nvim_win_get_height(Term._state.win) -- remember size
    vim.api.nvim_win_close(Term._state.win, false)
    Term._state.win = nil
  end
end

function Term.toggle()
  if term_win_valid() then Term.hide() else Term.open() end
end

_G.Term = Term

