-- =============================================================
-- Markdown viewing — render-markdown.nvim
-- =============================================================
-- Renders headings, code fences, tables, checkboxes, etc. directly in the
-- buffer (concealed) using the markdown/markdown_inline treesitter parsers
-- above. Toggle raw text at any time with :RenderMarkdown toggle.

-- Workaround: nvim-treesitter's markdown injections query uses
-- `#set-lang-from-info-string!` to pick a language for fenced code blocks
-- (e.g. ```lua). On this Neovim build that directive crashes
-- (vim.treesitter: "attempt to call method 'range' (a nil value)") as soon
-- as anything re-parses a restricted range, which render-markdown.nvim does
-- constantly. Overriding the query to drop that one directive avoids the
-- crash; frontmatter/html/inline injections are unaffected. Fenced code
-- still renders, just without embedded language-specific highlighting.
vim.treesitter.query.set("markdown", "injections", [[
((html_block) @injection.content
  (#set! injection.language "html")
  (#set! injection.combined)
  (#set! injection.include-children))

((minus_metadata) @injection.content
  (#set! injection.language "yaml")
  (#offset! @injection.content 1 0 -1 0)
  (#set! injection.include-children))

((plus_metadata) @injection.content
  (#set! injection.language "toml")
  (#offset! @injection.content 1 0 -1 0)
  (#set! injection.include-children))

([
  (inline)
  (pipe_table_cell)
] @injection.content
  (#set! injection.language "markdown_inline"))
]])

local ok_rm, rm = pcall(require, "render-markdown")
if ok_rm then
  rm.setup({})
end

