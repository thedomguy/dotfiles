-- =============================================================
-- lf file manager integration
-- =============================================================
-- Floating-window lf with:
--   * file selection round-tripped to nvim
--   * <c-p>/<c-f> inside lf -> quit lf, jump to FZF Files / Rg
--   * <c-x>/<c-v>/<c-t>     -> open selection in split / vsplit / tab
--   * <c-CR>                -> open in horizontal split (when terminal
--                              supports CSI-u / kitty keyboard protocol)
-- Pure Lua, no plugin dependency.

local Lf = {}
Lf._state = { win = nil, buf = nil, job = nil, closing = false }

-- lf snippet that adds nvim integration commands and keymaps. Written
-- once to a stable path and `source`-ed at lf launch. It does NOT modify
-- the user's lfrc; it only augments lf for sessions launched from nvim.
local lf_extra_config = vim.fn.stdpath("config") .. "/lf-nvim.lf"

local LF_EXTRA_BODY = [[
# Auto-generated by ~/.config/nvim/init.lua. Do not edit.

# Write the requested action ($1) into the file nvim is watching.
cmd nvim-action ${{
    printf '%s' "$1" > "$LF_NVIM_ACTION"
}}

# Quit lf without picking a file (used for fzf hand-off).
cmd nvim-files-quit :{{
    nvim-action files
    quit
}}
cmd nvim-rg-quit :{{
    nvim-action rg
    quit
}}

# Pick the current/selected file(s) and have nvim open them in a split.
cmd nvim-open-split :{{
    nvim-action split
    open
}}
cmd nvim-open-vsplit :{{
    nvim-action vsplit
    open
}}
cmd nvim-open-tab :{{
    nvim-action tab
    open
}}

# Make <enter> always pick the file (overrides user's `<enter> -> quit`
# from ~/.config/lf/lfrc when launched from nvim).
map <enter> open

# Hand-off to FZF in nvim
map <c-p> nvim-files-quit
map <c-f> nvim-rg-quit

# Splits / tab
map <c-x> nvim-open-split
map <c-v> nvim-open-vsplit
map <c-t> nvim-open-tab
]]

local function ensure_lf_config()
  local current = ""
  local f = io.open(lf_extra_config, "r")
  if f then current = f:read("*a"); f:close() end
  if current ~= LF_EXTRA_BODY then
    local out = io.open(lf_extra_config, "w")
    if out then out:write(LF_EXTRA_BODY); out:close() end
  end
end

local function floating_win(buf)
  local cols = vim.o.columns
  local rows = vim.o.lines
  local width = math.floor(cols * 0.85)
  local height = math.floor(rows * 0.80)
  local row = math.floor((rows - height) / 2)
  local col = math.floor((cols - width) / 2)
  return vim.api.nvim_open_win(buf, true, {
    relative = "editor",
    width = width,
    height = height,
    row = row,
    col = col,
    style = "minimal",
    border = "rounded",
    title = " lf ",
    title_pos = "center",
  })
end

local function read_first_line(path)
  if vim.fn.filereadable(path) ~= 1 then return "" end
  local lines = vim.fn.readfile(path)
  return (lines[1] or ""):gsub("%s+$", "")
end

local function read_selection(path)
  if vim.fn.filereadable(path) ~= 1 then return {} end
  local out = {}
  for _, line in ipairs(vim.fn.readfile(path)) do
    if line ~= "" then table.insert(out, line) end
  end
  return out
end

local function open_files(files, action)
  local cmd
  if action == "split" then
    cmd = "split"
  elseif action == "vsplit" then
    cmd = "vsplit"
  elseif action == "tab" then
    cmd = "tabedit"
  else
    cmd = "edit"
  end
  for _, f in ipairs(files) do
    vim.cmd(cmd .. " " .. vim.fn.fnameescape(f))
  end
end

-- Generate the lf integration snippet eagerly at startup.
ensure_lf_config()

--- Open lf rooted at `path` (file or dir).
---@param path string|nil
function Lf.open(path)
  ensure_lf_config()

  path = vim.fn.expand(path or ".")
  if path == "" then path = vim.fn.getcwd() end
  local target = vim.fn.isdirectory(path) == 1 and path or vim.fn.fnamemodify(path, ":h")

  local sel_file = vim.fn.tempname()
  local action_file = vim.fn.tempname()

  local buf = vim.api.nvim_create_buf(false, true)
  local win = floating_win(buf)

  -- lf args. -command runs after lfrc, so our `source` augments it.
  local cmd = {
    "lf",
    "-selection-path=" .. sel_file,
    "-command", "source " .. lf_extra_config,
    target,
  }

  local job = vim.fn.termopen(cmd, {
    env = { LF_NVIM_ACTION = action_file },
    on_exit = function(_, code)
      if Lf._state.closing then
        Lf._state = { win = nil, buf = nil, job = nil, closing = false }
        vim.fn.delete(sel_file)
        vim.fn.delete(action_file)
        return
      end

      if vim.api.nvim_win_is_valid(win) then
        vim.api.nvim_win_close(win, true)
      end
      if vim.api.nvim_buf_is_valid(buf) then
        vim.api.nvim_buf_delete(buf, { force = true })
      end

      local action = read_first_line(action_file)
      local files = read_selection(sel_file)
      vim.fn.delete(sel_file)
      vim.fn.delete(action_file)

      if code ~= 0 and action == "" then return end

      if action == "files" then
        vim.cmd("Files")
        return
      elseif action == "rg" then
        vim.cmd("Rg")
        return
      end

      open_files(files, action) -- "split" | "vsplit" | "tab" | ""
    end,
  })
  Lf._state = { win = win, buf = buf, job = job, closing = false }

  -- Terminal-mode niceties for this lf buffer:
  --   <C-CR> -> <C-x> so terminals that DO disambiguate Ctrl+Enter
  --             (kitty/WezTerm/Ghostty/iTerm2 w/ CSI-u) trigger the split action.
  --   <Esc>  is left to lf (lf uses it). Escape via <C-\\><C-n> still works.
  local map_opts = { buffer = buf, silent = true, nowait = true }
  vim.keymap.set("t", "<C-CR>",   "<C-x>", map_opts)
  vim.keymap.set("t", "<C-S-CR>", "<C-v>", map_opts)

  vim.cmd("startinsert")
end

function Lf.toggle(path)
  local st = Lf._state
  if st and st.win and vim.api.nvim_win_is_valid(st.win) then
    Lf._state.closing = true
    if st.job and st.job > 0 then vim.fn.jobstop(st.job) end
    if vim.api.nvim_win_is_valid(st.win) then vim.api.nvim_win_close(st.win, true) end
    if st.buf and vim.api.nvim_buf_is_valid(st.buf) then vim.api.nvim_buf_delete(st.buf, { force = true }) end
    Lf._state = { win = nil, buf = nil, job = nil, closing = false }
    return
  end
  Lf.open(path or vim.fn.getcwd())
end

-- :Lf [path]   →  open lf (defaults to cwd)
vim.api.nvim_create_user_command("Lf", function(opts)
  Lf.open(opts.args ~= "" and opts.args or vim.fn.getcwd())
end, { nargs = "?", complete = "file" })

