-- Hijack `nvim <dir>` so opening a directory launches lf.
-- Also open lf on plain `nvim` (no args) — mirrors Cursor's always-visible explorer.
--
-- Skipped under vscode-neovim: that extension spawns an embedded nvim with no
-- file args on every window open, which looks identical to plain `nvim` here
-- and would float lf over the editor on each Cursor launch. Cursor already has
-- its own explorer, and lf can't render correctly into the embedded UI grid
-- anyway. :Lf and the <leader>f / <leader>F / - mappings still work on demand.
local lf_hijack = vim.api.nvim_create_augroup("LfHijackNetrw", { clear = true })
vim.api.nvim_create_autocmd("VimEnter", {
  group = lf_hijack,
  callback = function()
    if vim.g.vscode then return end
    local arg = vim.fn.argv(0)
    vim.schedule(function()
      local dir = nil
      if type(arg) == "string" and arg ~= "" and vim.fn.isdirectory(arg) == 1 then
        vim.cmd("bdelete!")
        dir = arg
      elseif arg == "" or arg == nil then
        dir = vim.fn.getcwd()
      end

      if not dir then return end

      local entries = vim.fn.glob(dir .. "/*", false, true)
      if #entries == 0 then
        -- Empty directory: do nothing
        return
      elseif #entries == 1 and vim.fn.isdirectory(entries[1]) == 0 then
        -- Single file: open it directly without lf
        vim.cmd("edit " .. vim.fn.fnameescape(entries[1]))
      else
        -- Multiple entries: open lf
        Lf.open(dir)
      end
    end)
  end,
})

